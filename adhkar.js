const list = document.querySelector("#adhkar-list");
const categoryNav = document.querySelector("#adhkar-categories");
const progressCount = document.querySelector("#progress-count");
const progressHint = document.querySelector("#progress-hint");
const progressTrack = document.querySelector(".progress-track");
const progressFill = document.querySelector("#progress-fill");
const today = new Date().toLocaleDateString("en-CA");
const storageKey = `noor-adhkar-${today}`;
let currentCategory = "morning";
let savedCounts = {};
let storageNotice = "";

try {
    const savedValue = localStorage.getItem(storageKey);
    if (savedValue) {
        const parsed = JSON.parse(savedValue);
        if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
            savedCounts = parsed;
        }
    }
} catch (error) {
    storageNotice = "Daily count storage is unavailable in this browser; your counts will reset when you leave this page.";
}

function getCount(category, index) {
    const value = savedCounts[`${category}-${index}`];
    return Number.isInteger(value) && value >= 0 ? value : 0;
}

function saveCounts() {
    try {
        localStorage.setItem(storageKey, JSON.stringify(savedCounts));
        storageNotice = "";
    } catch (error) {
        storageNotice = "Daily count storage is unavailable in this browser; your counts will reset when you leave this page.";
    }
}

function updateProgress() {
    const entries = adhkar[currentCategory];
    const total = entries.reduce((sum, entry) => sum + entry.count, 0);
    const completed = entries.reduce((sum, entry, index) => sum + Math.min(getCount(currentCategory, index), entry.count), 0);
    const completedItems = entries.filter((entry, index) => getCount(currentCategory, index) >= entry.count).length;
    const percent = total ? Math.round((completed / total) * 100) : 0;

    progressCount.textContent = `${completedItems} of ${entries.length} completed`;
    progressHint.textContent = `${completed} of ${total} repetitions${storageNotice ? ` · ${storageNotice}` : ""}`;
    progressFill.style.width = `${percent}%`;
    progressTrack.setAttribute("aria-valuenow", String(percent));
}

function createAdhkarCard(entry, index) {
    const card = document.createElement("article");
    card.className = "adhkar-card";

    const cardTop = document.createElement("div");
    cardTop.className = "adhkar-card-top";
    const reference = document.createElement("span");
    reference.className = "hadith-reference";
    reference.textContent = entry.reference;
    cardTop.append(reference);

    const arabic = document.createElement("p");
    arabic.className = "adhkar-arabic";
    arabic.lang = "ar";
    arabic.dir = "rtl";
    arabic.textContent = entry.arabic;

    const transliteration = document.createElement("p");
    transliteration.className = "adhkar-transliteration";
    transliteration.textContent = entry.transliteration;

    const meaning = document.createElement("p");
    meaning.className = "adhkar-meaning";
    meaning.textContent = entry.meaning;

    const cardFooter = document.createElement("div");
    cardFooter.className = "adhkar-card-footer";
    const counter = document.createElement("div");
    counter.className = "counter-display";
    counter.setAttribute("aria-live", "polite");
    const countValue = document.createElement("strong");
    countValue.textContent = String(Math.min(getCount(currentCategory, index), entry.count));
    const countGoal = document.createElement("span");
    countGoal.textContent = `/ ${entry.count}`;
    counter.append(countValue, countGoal);

    const actions = document.createElement("div");
    actions.className = "counter-actions";
    const countButton = document.createElement("button");
    countButton.type = "button";
    countButton.className = "count-button";
    countButton.textContent = "Count";
    countButton.setAttribute("aria-label", `Count ${entry.transliteration}, target ${entry.count}`);
    const resetButton = document.createElement("button");
    resetButton.type = "button";
    resetButton.className = "counter-reset";
    resetButton.textContent = "Reset";
    resetButton.setAttribute("aria-label", `Reset count for ${entry.transliteration}`);

    countButton.addEventListener("click", () => {
        const key = `${currentCategory}-${index}`;
        savedCounts[key] = Math.min(getCount(currentCategory, index) + 1, entry.count);
        countValue.textContent = String(savedCounts[key]);
        countButton.disabled = savedCounts[key] >= entry.count;
        saveCounts();
        updateProgress();
    });
    resetButton.addEventListener("click", () => {
        delete savedCounts[`${currentCategory}-${index}`];
        countValue.textContent = "0";
        countButton.disabled = false;
        saveCounts();
        updateProgress();
    });
    countButton.disabled = getCount(currentCategory, index) >= entry.count;
    actions.append(countButton, resetButton);
    cardFooter.append(counter, actions);
    card.append(cardTop, arabic, transliteration, meaning, cardFooter);
    return card;
}

function renderCategory(category) {
    currentCategory = category;
    list.replaceChildren();
    adhkar[category].forEach((entry, index) => {
        list.append(createAdhkarCard(entry, index));
    });
    categoryNav.querySelectorAll(".category-tab").forEach((button) => {
        const isActive = button.dataset.category === category;
        button.classList.toggle("is-active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });
    updateProgress();
}

categoryNav.addEventListener("click", (event) => {
    const button = event.target.closest("[data-category]");
    if (button && adhkar[button.dataset.category]) {
        renderCategory(button.dataset.category);
    }
});

renderCategory(currentCategory);
